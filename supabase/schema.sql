-- ---------------------------------------------------------------------------
-- Rename the earlier task naming to ideas. This preserves existing rows.
-- ---------------------------------------------------------------------------
do $$
begin
  if exists (
    select 1
    from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' and t.typname = 'task_status'
  ) and not exists (
    select 1
    from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' and t.typname = 'idea_status'
  ) then
    alter type public.task_status rename to idea_status;
  end if;

  if to_regclass('public.tasks') is not null
     and to_regclass('public.ideas') is null then
    alter table public.tasks rename to ideas;
  end if;
end
$$;

-- ---------------------------------------------------------------------------
-- Enums
-- ---------------------------------------------------------------------------
do $$
begin
  create type public.idea_status as enum (
    'planned',
    'in_progress',
    'feature_request',
    'completed'
  );
exception
  when duplicate_object then null;
end
$$;

do $$
begin
  create type public.profile_status as enum (
    'failed',
    'active',
    'inactive',
    'archived'
  );
exception
  when duplicate_object then null;
end
$$;

-- Add the value for databases created before `inactive` existed.
alter type public.profile_status add value if not exists 'inactive';

do $$
begin
  create type public.note_status as enum ('active', 'archived');
exception
  when duplicate_object then null;
end
$$;

-- ---------------------------------------------------------------------------
-- profiles: one row per Supabase auth user
-- status: failed until the first successful authenticated request, then active.
-- Deleting an account sets status to archived (soft delete).
-- ---------------------------------------------------------------------------
create table if not exists public.profiles (
  id             integer generated by default as identity primary key,
  user_id        uuid not null unique references auth.users (id) on delete cascade,
  email          text not null default '',
  full_name      text,
  -- Supabase's own bcrypt hash, copied from auth.users.encrypted_password.
  -- Plain-text passwords are never stored anywhere.
  password_hash  text,
  status         public.profile_status not null default 'failed',
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

-- Keep the schema re-runnable on databases created by an earlier version.
alter table public.profiles drop column if exists avatar_url;
alter table public.profiles
  add column if not exists status public.profile_status not null default 'failed';
alter table public.profiles
  add column if not exists password_hash text;

-- ---------------------------------------------------------------------------
-- notes: title + a single rich-text description box per note.
-- Deleting a note sets status to archived (soft delete).
-- ---------------------------------------------------------------------------
create table if not exists public.notes (
  id            integer generated by default as identity primary key,
  user_id       uuid not null references auth.users (id) on delete cascade,
  title         text not null default 'Untitled note',
  content       jsonb not null default '{"type":"doc","content":[{"type":"paragraph"}]}'::jsonb,
  content_text  text not null default '',
  status        public.note_status not null default 'active',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

alter table public.notes
  add column if not exists title text not null default 'Untitled note';
alter table public.notes
  add column if not exists status public.note_status not null default 'active';

-- ---------------------------------------------------------------------------
-- ideas: title + rich-text description + kanban status
-- ---------------------------------------------------------------------------
create table if not exists public.ideas (
  id                integer generated by default as identity primary key,
  user_id           uuid not null references auth.users (id) on delete cascade,
  title             text not null,
  description       jsonb not null default '{"type":"doc","content":[{"type":"paragraph"}]}'::jsonb,
  description_text  text not null default '',
  status            public.idea_status not null default 'planned',
  position          integer not null default 0,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- activity_logs is no longer used.
-- ---------------------------------------------------------------------------
drop table if exists public.activity_logs;

-- ---------------------------------------------------------------------------
-- Indexes
-- ---------------------------------------------------------------------------
drop index if exists public.notes_user_updated_idx;

create index if not exists notes_user_status_updated_idx
  on public.notes (user_id, status, updated_at desc);

drop index if exists public.tasks_user_status_position_idx;

create index if not exists ideas_user_status_position_idx
  on public.ideas (user_id, status, position);

-- ---------------------------------------------------------------------------
-- updated_at trigger
-- ---------------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
  before update on public.profiles
  for each row execute function public.set_updated_at();

drop trigger if exists notes_set_updated_at on public.notes;
create trigger notes_set_updated_at
  before update on public.notes
  for each row execute function public.set_updated_at();

drop trigger if exists tasks_set_updated_at on public.ideas;
drop trigger if exists ideas_set_updated_at on public.ideas;
create trigger ideas_set_updated_at
  before update on public.ideas
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- Automatically create a profile when a user signs up (email or Google).
-- The profile starts as `failed`; it becomes `active` on the first successful
-- authenticated API request (see GET /api/profile).
-- ---------------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (user_id, email, full_name, password_hash)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name'),
    new.encrypted_password
  )
  on conflict (user_id) do update
    set email = excluded.email,
        password_hash = coalesce(excluded.password_hash, public.profiles.password_hash),
        updated_at = now();

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Keep the copy in sync when a password is changed.
create or replace function public.handle_user_password_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.profiles
  set password_hash = new.encrypted_password
  where user_id = new.id;

  return new;
end;
$$;

drop trigger if exists on_auth_user_password_changed on auth.users;
create trigger on_auth_user_password_changed
  after update of encrypted_password on auth.users
  for each row execute function public.handle_user_password_change();

-- Backfill existing accounts from Supabase Auth.
update public.profiles p
set password_hash = u.encrypted_password
from auth.users u
where p.user_id = u.id
  and u.encrypted_password is not null
  and p.password_hash is distinct from u.encrypted_password;

-- ---------------------------------------------------------------------------
-- Row Level Security
-- The Express API uses the service-role key (which bypasses RLS), but these
-- policies keep the tables safe if they are ever queried from the browser.
-- ---------------------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.notes enable row level security;
alter table public.ideas enable row level security;

drop policy if exists "Users can view their own profile" on public.profiles;
create policy "Users can view their own profile"
  on public.profiles for select
  using (auth.uid() = user_id);

drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile"
  on public.profiles for update
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "Users can insert their own profile" on public.profiles;
create policy "Users can insert their own profile"
  on public.profiles for insert
  with check (auth.uid() = user_id);

-- Defense in depth: even if the browser talks to Supabase directly, a user may
-- only change their full name. Status changes stay server-side, and the password
-- hash is never selectable from the browser.
revoke update on public.profiles from authenticated;
grant update (full_name) on public.profiles to authenticated;

revoke select on public.profiles from authenticated;
grant select (
  id,
  user_id,
  email,
  full_name,
  status,
  created_at,
  updated_at
) on public.profiles to authenticated;

drop policy if exists "Users manage their own notes" on public.notes;
create policy "Users manage their own notes"
  on public.notes for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "Users manage their own tasks" on public.ideas;
drop policy if exists "Users manage their own ideas" on public.ideas;
create policy "Users manage their own ideas"
  on public.ideas for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);
